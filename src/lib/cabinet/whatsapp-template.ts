/** WhatsApp message the team sends a new client together with the personal cabinet link. */

export function welcomeMessage(opts: { name?: string; link: string; curator?: string; service?: string }) {
  const hello = opts.name?.trim() ? `Здравствуйте, ${opts.name.trim()}! 👋` : "Здравствуйте! 👋";
  const curator = opts.curator?.trim() || "Мухаммад";
  if (opts.service === "keta") {
    return [
      hello,
      `Меня зовут ${curator}, я куратор компании AlemWay. Если появятся вопросы, пишите сюда.`,
      "",
      "Оформление K-ETA проходит в вашем личном кабинете на нашем сайте.",
      "",
      "🔗 Ваш личный кабинет:",
      opts.link,
      "⚠️ Ссылка личная, никому её не пересылайте.",
      "",
      "Заполните анкету латиницей (как в загранпаспорте), загрузите скан паспорта и фото и нажмите «Отправить». Дальше мы подадим заявку и напишем вам здесь.",
    ].join("\n");
  }
  return [
    hello,
    `Меня зовут ${curator}, я куратор компании AlemWay. Буду сопровождать вас на всех этапах. Если появятся вопросы, пишите сюда.`,
    "",
    "Всё оформление теперь проходит в вашем личном кабинете на нашем сайте. Ничего не нужно присылать в WhatsApp, всё делается в одном месте.",
    "",
    "🔗 Ваш личный кабинет:",
    opts.link,
    "⚠️ Ссылка личная, никому её не пересылайте.",
    "",
    "Что нужно сделать:",
    "",
    "1. Загрузите документы (фото или PDF, большие файлы сайт сожмёт сам):",
    "• справку с места учёбы на английском с печатью университета (обязательно)",
    "• скан загранпаспорта, разворот с фото (нужен до января; если его ещё нет, впишите имя и фамилию латиницей)",
    "• академический календарь вуза, если есть",
    "",
    "2. Заполните несколько полей: телефон, город, категорию прав (если есть). Вуз, специальность, даты учёбы и каникул пишите, только если их нет в справке.",
    "",
    "3. Нажмите «Отправить и получить декларацию»",
    "Сайт сам проверит документы и заполнит официальную декларацию ZAV. Если чего-то не хватает, он подскажет, что исправить.",
    "",
    "4. Скачайте декларацию и распечатайте её в 2 экземплярах",
    "Отнесите оба экземпляра в деканат: на каждом должны поставить подпись и печать вуза в поле 21 (внизу второй страницы). Сами в этом поле ничего не пишите.",
    "",
    "5. Загрузите сканы обоих подписанных экземпляров (каждый отдельным файлом) и нажмите «Отправить декларацию с печатью»",
    "",
    "✅ Всё! Дальше мы отправляем документы партнёру и ждём разрешение ZAV, обычно это несколько недель. Все этапы видны в вашем кабинете, а когда ZAV придёт, мы сразу напишем вам здесь.",
    "",
    "Если ссылка перестала открываться, напишите нам, и мы пришлём новую.",
  ].join("\n");
}
